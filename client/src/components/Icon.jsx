// Guess an icon from a social label so new links added in the admin get one automatically.
export const iconFor = (label = "") => {
  const l = label.toLowerCase();
  if (l.includes("github") || l.includes("gitlab")) return "github";
  if (l.includes("linkedin")) return "linkedin";
  if (l.includes("mail")) return "mail";
  return "code";
};

export default function Icon({ name, size = 16 }) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
      <path d={paths[name] || paths.code} />
    </svg>
  );
}
